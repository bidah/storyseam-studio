// Vendor the shared proxy route table into the desktop package. The desktop app
// is a standalone npm package (electron-builder can't reach outside it), so the
// ONE source of truth — src/lib/routeTable.js — is copied here before every
// dev run / build (pre-hooks on dev/start/dist). The copy is gitignored; edit
// the original only. Same pattern as render-fn's `npm run sync`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "src", "lib", "routeTable.js");
const dest = join(here, "..", "main", "routeTable.js");

const body = readFileSync(src, "utf8");
writeFileSync(
  dest,
  "// GENERATED by scripts/sync-shared.mjs from src/lib/routeTable.js — DO NOT EDIT.\n" + body,
);
console.log("[desktop] synced route table → main/routeTable.js");
