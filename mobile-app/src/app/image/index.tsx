import { useEffect } from 'react';
import { useLocalSearchParams } from 'expo-router';
import { VisualWorldSurface } from '@/components/story/visual-world';
import { setAgentMode } from '@/lib/agent/pill-mode';

// Visual world, inside the image modal — the same surface the Story tab used to
// render as its `World › Visual world` segment, now the modal's only screen.
//
// `suppressAccessory={false}`: the modal already covers the tab bar, and taking
// the pill away would re-lay the bar underneath and animate it back in on
// dismiss. (Docking a composer is still why that suppression exists — it just
// doesn't apply from in here. Same call the chat modal makes.)
//
// `focus` / `draft` are the tab bar's hand-offs: opening from the pill puts the
// caret in the prompt field, and the pill's mic carries a dictated prompt here to
// be generated BY HAND — never fired on arrival (lib/agent/voice-capture.tsx).
export default function ImageScreen() {
  const { focus, draft, dk } = useLocalSearchParams<{
    focus?: string;
    draft?: string;
    dk?: string;
  }>();

  // Say so, in case we got here without going through the toggle — the agent's
  // `navigate` command and a deep link both land on this route directly, and the
  // header's toggle reads the same store the pill does (lib/agent/pill-mode.ts).
  useEffect(() => setAgentMode('image'), []);

  return (
    <VisualWorldSurface
      suppressAccessory={false}
      focus={focus === '1'}
      draft={draft}
      draftKey={dk}
    />
  );
}
