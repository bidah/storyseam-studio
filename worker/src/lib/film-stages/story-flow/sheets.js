// The story flow's "Character & location sheets" stage (/story-flow — the
// Seedance 2.5 Film; see film-plan.ts › The STORY FLOW).
//
// The Director's sheets stage draws one dense model sheet per subject, because
// a Director pin is a single frame drawn against at most nine references. A
// Seedance 2.5 generation takes up to 30 images, each bound by name in the
// prompt (@Image1 defines…), and the Seedance skill is explicit about what it
// wants: "prefer separate views over one dense collage for an important
// subject", and a scene reference that carries no people. So the recipe here is
// different:
//
//   - ONE style frame first — the anchor every other sheet is drawn against, so
//     the cast comes out in one hand. It is NOT sent to Seedance (a style frame
//     read as a reference leaks its own composition); the look reaches the
//     video as words.
//   - Per CHARACTER, two images of the same person: a full-body turnaround
//     (front, 3/4, side, back) and a large face portrait.
//   - Per PLACE, one empty establishing plate: the layout, architecture and
//     light, with no people in it.
//   - Per PROP, one object sheet: the object alone, from several sides, no
//     hands and nobody holding it. A character is drawn EMPTY-HANDED — a prop
//     painted into a turnaround is welded to that figure in every shot (it
//     reappears in scenes it has left, or duplicates when the story hands it
//     over) — so a prop reaches a segment only as its OWN reference, bound
//     where the Shot list says it is in the scene.
//
// Each carries an `inherit` note — the traits a segment's reference map says
// that image defines — written by the art department beside its prompt.
//
// Filed on the Film's Director Series exactly as the Director flow files its
// sheets (so the project's Director tab and the agent's tools see them), found
// again by `filmId` on a retry, and never paid for twice.
import { filmStyleFor, MAX_STORY_FLOW_SHEETS } from "../../film-plan.ts";
import { absolutize, upsertModelSheet } from "../../director.js";
import { artSettings } from "../../series.ts";
import { readWorld } from "../../../routes/world.js";
import { SHEET_MODEL, drawSheet, ensureFilmSeries } from "../sheets.js";
import { linkSheetsToWorld } from "../world-links.js";

const str = (v) => (typeof v === "string" ? v : v == null ? "" : String(v)).trim();
const key = (name) => str(name).toLowerCase().replace(/\s+/g, " ");

export const VIEW_LABEL = { body: "turnaround", face: "face", plate: "plate", prop: "prop sheet" };

// A character sheet is the PERSON only, whatever the World's appearance note
// or the writer's prompt says they carry — first and last, as the plate's
// EMPTY is, because an image model weighs the opening words most.
export const EMPTY_HANDED =
  "EMPTY-HANDED: the character holds, carries and wears no props — no weapon, bag, tool, phone, device, instrument, " +
  "book, cup or object of any kind, nothing in the hands, on the back or at the belt; hands open and visible.";
// A prop sheet is the OBJECT only.
export const OBJECT_ONLY =
  "The object ALONE: no hands, no people, no characters, no creatures, nobody holding or wearing it.";

// ── The writing half ────────────────────────────────────────────────────────

export function storyFlowSheetMessages({ idea, world, look }) {
  const cast = (world.characters || [])
    .map((c) => `- ${c.name}${c.role ? ` (${c.role})` : ""}: ${c.appearance || c.traits || "(no appearance given — design one)"}`)
    .join("\n");
  const places = (world.locations || [])
    .map((l) => `- ${l.name}: ${l.description || "(no description given — design one)"}`)
    .join("\n");
  const props = (world.props || [])
    .map((p) => `- ${p.name}${p.owner ? ` (carried by ${p.owner})` : ""}: ${p.description || "(no description given — design one)"}`)
    .join("\n");
  const system = [
    "You are the art department of StorySeam's story flow. A short film will be generated by Seedance 2.5,",
    "a video model that takes REFERENCE IMAGES and binds each one by name in its prompt (\"@Image1 defines",
    "Mira's face and hair\"). You write the prompts for those reference images. Nobody will be asked anything:",
    "decide every design detail yourself, concretely.",
    "",
    "THE FILM'S LOOK IS ALREADY CHOSEN — design everything to belong in it, and never drift from it:",
    look.look,
    "",
    "Write:",
    "- `style`: ONE style frame — a single painted/rendered frame of the film's world in this look (palette,",
    "  light, texture, line). No characters in it.",
    "- Per CHARACTER in the World (use the name EXACTLY):",
    "  `identity` — one sentence of the traits every shot must keep (face, hair, build, clothing, colours),",
    "   written as a visual note. NEVER a prop: nothing they hold, carry or use — props are drawn apart;",
    "  `body` — an image prompt for a clean full-body TURNAROUND: front, three-quarter, side profile and back",
    "   views of the SAME figure in a row, identical outfit and proportions in every view, EMPTY-HANDED (no",
    "   props, nothing held or carried, hands open), plain light-grey background, even flat light, no text,",
    "   no labels, nobody else;",
    "  `face` — an image prompt for a large head-and-shoulders PORTRAIT of the same character, front-facing,",
    "   neutral expression, nothing held, plain light-grey background, even light, no text.",
    "  Even when the World says a character carries something, draw them WITHOUT it: every object is a PROP.",
    "- Per PLACE in the World (use the name EXACTLY):",
    "  `layout` — one sentence of what a scene set there must keep (architecture, layout, landmarks, light);",
    "  `plate` — an image prompt for ONE wide establishing view of the place, EMPTY of people and creatures,",
    "   eye-level, the light of the story, no text.",
    "- Per PROP in the World (use the name EXACTLY) — an object the story turns on:",
    "  `design` — one sentence of what every shot must keep (shape, size, material, colours, wear, markings);",
    "  `sheet` — an image prompt for ONE prop sheet: the object alone, centred, seen from the front, the side",
    "   and three-quarter in a row, true to scale cues, plain light-grey background, even flat light, no hands,",
    "   no people, no text, no labels.",
    "",
    "Also write ONE `renderClause`: the house-style sentence appended to every prompt for you (do not repeat",
    "it inside the prompts).",
    "",
    "Answer with ONE JSON object and nothing else:",
    '{ "renderClause": string, "style": { "prompt": string },',
    '  "characters": [{ "name": string, "identity": string, "body": string, "face": string }],',
    '  "locations": [{ "name": string, "layout": string, "plate": string }],',
    '  "props": [{ "name": string, "design": string, "sheet": string }] }',
  ].join("\n");
  const user = [
    `The Idea: ${idea || "(none)"}`,
    `Title: ${world.title || "(untitled)"}`,
    world.logline ? `Logline: ${world.logline}` : "",
    "",
    "Characters:",
    cast || "(none)",
    "",
    "Places:",
    places || "(none)",
    "",
    "Props:",
    props || "(none)",
  ].filter((l) => l !== "").join("\n");
  return [
    { role: "system", content: system },
    { role: "user", content: user },
  ];
}

/**
 * The model's answer + the World → the ordered, capped sheets to draw.
 * Style first, then each character's turnaround, each place's plate, each
 * prop's sheet, then the face portraits — the cap (MAX_STORY_FLOW_SHEETS) gives
 * way from the tail, so a crowded World loses its last faces before any
 * subject goes unreferenced. A subject the model forgot is written from the
 * World's own note.
 *
 * → [{ kind: 'style'|'character'|'location'|'prop', view: 'style'|'body'|'face'|'plate'|'prop',
 *      subject, name, prompt, inherit }]
 */
export function planStoryFlowSheets(answer, world, look, max = MAX_STORY_FLOW_SHEETS) {
  const clause = [`In the film's look: ${look.look}`, str(answer?.renderClause)].filter(Boolean).join(" ");
  const withClause = (p) => [str(p), clause].filter(Boolean).join("\n\n");
  const byName = (list) => new Map((Array.isArray(list) ? list : []).filter((x) => str(x?.name)).map((x) => [key(x.name), x]));
  const chars = byName(answer?.characters);
  const places = byName(answer?.locations);
  const propsW = byName(answer?.props);

  const style = {
    kind: "style",
    view: "style",
    subject: "House style",
    name: "House style",
    prompt: withClause(str(answer?.style?.prompt) || "A style frame for the whole film: its palette, light, texture and line. No characters."),
    inherit: "",
  };

  const bodies = [];
  const faces = [];
  for (const c of (world.characters || []).filter((x) => str(x?.name))) {
    const w = chars.get(key(c.name)) || {};
    const note = c.appearance || c.traits || c.role || "a figure from this story";
    const identity = str(w.identity) || note;
    bodies.push({
      kind: "character", view: "body", subject: c.name, name: `${c.name} — ${VIEW_LABEL.body}`, inherit: identity,
      prompt: withClause([EMPTY_HANDED, str(w.body) ||
        `A full-body character turnaround of ${c.name}: ${note}. Front, three-quarter, side profile and back views ` +
        "of the same figure in a row, identical outfit and proportions, plain light-grey background, even light. No text, nobody else.", EMPTY_HANDED].join(" ")),
    });
    faces.push({
      kind: "character", view: "face", subject: c.name, name: `${c.name} — ${VIEW_LABEL.face}`, inherit: identity,
      prompt: withClause([str(w.face) ||
        `A head-and-shoulders portrait of ${c.name}: ${note}. Front-facing, neutral expression, plain light-grey background, even light. No text.`,
      "Nothing held, nothing in frame but the character."].join(" ")),
    });
  }
  // A plate is EMPTY whatever the writer's prompt says: film-6767fc11's
  // "Brownstone Block" plate came back with a skateboarding kid in it, a
  // stranger the video model is then free to cast.
  const EMPTY = "The place alone and EMPTY: no people, no figures, no characters, no animals anywhere in the frame.";
  const plates = (world.locations || []).filter((x) => str(x?.name)).map((l) => {
    const w = places.get(key(l.name)) || {};
    return {
      kind: "location", view: "plate", subject: l.name, name: `${l.name} — ${VIEW_LABEL.plate}`,
      inherit: str(w.layout) || l.description || "",
      // First as well as last: an image model weighs the opening words most,
      // and a writer's plate prompt has been known to put a person in.
      prompt: withClause([EMPTY, str(w.plate) ||
        `A wide establishing view of ${l.name}: ${l.description || "a place from this story"}. Eye-level. No text.`, EMPTY].join(" ")),
    };
  });
  const props = (world.props || []).filter((x) => str(x?.name)).map((p) => {
    const w = propsW.get(key(p.name)) || {};
    return {
      kind: "prop", view: "prop", subject: p.name, name: `${p.name} — ${VIEW_LABEL.prop}`,
      inherit: str(w.design) || p.description || "",
      prompt: withClause([OBJECT_ONLY, str(w.sheet) ||
        `A prop sheet of ${p.name}: ${p.description || "an object from this story"}. The same object seen from the front, the side ` +
        "and three-quarter in a row, plain light-grey background, even light. No text, no labels.", OBJECT_ONLY].join(" ")),
    };
  });
  return [style, ...bodies, ...plates, ...props, ...faces].slice(0, max);
}

// ── The stage ───────────────────────────────────────────────────────────────

/**
 * deps (optional): { readWorld, fal, fetch, putMedia, sleep, now } — as the
 * Director sheets stage takes them.
 *
 * result = { seriesId, style: { name, imageUrl }, refs: [{ kind, view, subject,
 *            name, imageUrl, inherit }] } — `refs` are what segments bind.
 */
export async function runStoryFlowSheetsStage({ job, results, env, model }, deps = {}) {
  const pid = job.projectId;
  const world = await (deps.readWorld || readWorld)(env, pid);
  if (!world?.characters?.length) throw new Error("There is no World to draw sheets from.");
  const idea = results?.world?.idea || "";
  const look = filmStyleFor({ style: results?.look?.style || job.style, prompt: job.prompt });

  const answer = await model.json({ messages: storyFlowSheetMessages({ idea, world, look }), maxTokens: 8000, temperature: 0.7 });
  const plan = planStoryFlowSheets(answer, world, look);

  const series = await ensureFilmSeries(env, pid, job, {
    title: world.title || results?.world?.title,
    prompt: [look.look, look.lock, idea, world.logline].filter(Boolean).join("\n\n"),
  });
  const aspectRatio = artSettings(series).sheets.aspectRatio;
  const filed = new Map((series.modelSheets || []).filter((s) => s.imageUrl).map((s) => [s.name, s]));

  const failures = [];
  const drawGroup = async (group, refs) => {
    const drawn = await Promise.all(group.map(async (sheet) => {
      const have = filed.get(sheet.name);
      if (have) return { ...sheet, imageUrl: have.imageUrl, sourceUrl: null, reused: true };
      try {
        const refUrls = refs
          .map((r) => r.sourceUrl || absolutize(env, pid, r.imageUrl))
          .filter((u) => /^https?:\/\//i.test(u));
        return { ...sheet, ...(await drawSheet({ env, pid, job, sheet, aspectRatio, refs: refUrls }, deps)) };
      } catch (err) {
        failures.push(String(err?.message || err));
        return null;
      }
    }));
    const out = [];
    for (const sheet of drawn) {
      if (!sheet) continue;
      if (!sheet.reused) {
        const res = await upsertModelSheet(env, pid, series.id, {
          // A Series knows character / location / style sheets; a prop is
          // filed as a "character" — a figure held still across the piece,
          // as the Director's own sheets file a machine (../sheets.js). The
          // Film's refs keep `kind: "prop"`, which is what segments bind by.
          kind: sheet.kind === "prop" ? "character" : sheet.kind,
          name: sheet.name,
          prompt: sheet.prompt,
          imageUrl: sheet.imageUrl,
          model: SHEET_MODEL.label,
          refs: refs.map((r) => r.imageUrl),
        });
        if (!res.ok) {
          failures.push(`"${sheet.name}" could not be filed: ${Object.values(res.issues || { e: "no such Series" }).join("; ")}`);
          continue;
        }
      }
      out.push(sheet);
    }
    return out;
  };

  const [style] = await drawGroup(plan.filter((s) => s.view === "style"), []);
  const subjects = await drawGroup(plan.filter((s) => s.view !== "style"), style ? [style] : []);
  if (failures.length) {
    throw new Error(`${failures.length} of ${plan.length} sheets failed — ${failures.join("; ")}`);
  }

  const refs = subjects.map((s) => ({
    kind: s.kind, view: s.view, subject: s.subject, name: s.name, imageUrl: s.imageUrl, inherit: s.inherit,
  }));
  const people = new Set(refs.filter((r) => r.kind === "character").map((r) => r.subject)).size;
  const placesN = refs.filter((r) => r.view === "plate").length;
  const propsN = refs.filter((r) => r.kind === "prop").length;
  // The Bible shows them: face → the character's sheet, turnaround → its
  // miniature (the full figure for wide shots), plate → the place's sheet,
  // prop sheet → the prop's.
  const FIELD = { face: "sheetImage", body: "miniatureImage", plate: "sheetImage", prop: "sheetImage" };
  const linked = await (deps.linkSheetsToWorld || linkSheetsToWorld)(env, pid, subjects.map((s) => ({
    kind: s.kind, subject: s.subject, name: s.name, imageUrl: s.imageUrl, field: FIELD[s.view],
  })));
  const n = (k, one) => `${k} ${one}${k === 1 ? "" : "s"}`;
  return {
    summary: `${n(refs.length + (style ? 1 : 0), "sheet")} — ${n(people, "character")} (turnaround + face), ${n(placesN, "place")}` +
      `${propsN ? `, ${n(propsN, "prop")}` : ""}${linked ? ` · ${linked} linked in the Bible` : ""}`,
    result: { seriesId: series.id, style: style ? { name: style.name, imageUrl: style.imageUrl } : null, refs },
  };
}
